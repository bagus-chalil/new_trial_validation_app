<?php
/**
 * Generates warehouse/sql/*.sql and warehouse/docs/table_mapping.md from the
 * schema of the LOCAL dev MySQL databases. Read-only: only SELECTs on
 * information_schema. DB credentials are read from each app's .env at run
 * time and never written to any output.
 *
 *   php warehouse/tools/generate.php
 *
 * Design: raw = faithful copy of the source (same column types as the
 * mysql_fdw foreign tables, created with CREATE TABLE AS ... WITH NO DATA),
 * minus sensitive columns. Type cleanup (smallint -> boolean etc.) happens in
 * staging, not here.
 */

$root = dirname(__DIR__, 2);

$sources = [
    'trial' => [
        'db' => 'trial_validation_system', 'env' => "$root/new_trial_validation_app/.env",
        'fdw' => 'fdw_trial',
        'categories' => [
            'framework' => ['cache', 'cache_locks', 'failed_jobs', 'job_batches', 'jobs', 'migrations', 'password_reset_tokens', 'sessions', 'sso_tickets'],
            'user_data' => ['users'],
            'ai_output' => ['ai_bot_aliases', 'ai_bot_interactions', 'ai_data_flags', 'ai_learning_runs', 'ai_lessons'],
        ],
    ],
    'ipc' => [
        'db' => 'ipc_system', 'env' => "$root/ipc_app/.env",
        'fdw' => 'fdw_ipc',
        'categories' => [
            'framework' => ['cache', 'cache_locks', 'failed_jobs', 'job_batches', 'jobs', 'migrations', 'password_reset_tokens', 'sessions'],
            'user_data' => ['users'],
            'import_log' => ['master_imports', 'master_import_issues'],
        ],
    ],
];

// Columns never copied into raw.
const SENSITIVE_COLS = '/(^|_)(password|password_hash|remember_token|token|secret|ip_address|user_agent)$/i';

// Free-text/JSON audit columns that can embed password hashes (confirmed:
// activity_logs module=USER rows contain a "password_hash" key). Redacted to
// NULL when they mention these words.
$redact = [
    'trial.activity_logs' => ['old_data', 'new_data'],
    'trial.audit_logs' => ['old_data', 'new_data'],
];
const REDACT_REGEX = 'password|passwd|token|secret';

function pdo(string $envFile, string $db): PDO
{
    $raw = file_get_contents($envFile);
    preg_match('/^DB_USERNAME=(.*)$/m', $raw, $u);
    preg_match('/^DB_PASSWORD=(.*)$/m', $raw, $p);

    return new PDO("mysql:host=127.0.0.1;dbname=$db", trim($u[1]), trim($p[1]), [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
}

$ddl = ["-- GENERATED by warehouse/tools/generate.php — do not edit by hand.\n-- Run as cosmax_dwh_admin (or dwh_admin) in database cosmax_dwh.\n-- raw = faithful copy of source, minus sensitive columns. Idempotent.\n\nBEGIN;\n"];
$load = ["-- GENERATED by warehouse/tools/generate.php — do not edit by hand.\n-- Run as cosmax_dwh_etl. Full refresh: each table is truncated and reloaded\n-- in its own transaction. Reads LIVE MySQL through mysql_fdw: run off-peak,\n-- one source at a time if in doubt.\n"];
$verify = ["-- GENERATED. Row-count check: source (fdw) vs raw.\n"];
$doc = ["# Table mapping — MySQL → `raw`\n\nGenerated by `warehouse/tools/generate.php` from the local dev schema (verified equal to the VM: 42 + 31 foreign tables). Row counts are InnoDB estimates from the dev copy.\n\n`raw` table name = `<source>__<mysql table>`. Categories: **domain** (loaded), **framework** / **ai_output** / **import_log** (skipped by default; edit the arrays at the top of the generator to change).\n"];
$verifyRows = [];
$summary = [];

foreach ($sources as $src => $cfg) {
    $pdo = pdo($cfg['env'], $cfg['db']);
    $db = $cfg['db'];
    $tables = $pdo->query("select table_name, table_rows from information_schema.tables where table_schema='$db' and table_type='BASE TABLE' order by 1")->fetchAll(PDO::FETCH_KEY_PAIR);

    $doc[] = "\n## Source: `$src` (`$db` → `{$cfg['fdw']}`)\n\n| MySQL table | Category | ~Rows | raw table | PK | Dropped cols | Redacted cols |\n|---|---|---:|---|---|---|---|";
    $included = 0;

    foreach ($tables as $table => $rows) {
        $cat = 'domain';
        foreach ($cfg['categories'] as $name => $list) {
            if (in_array($table, $list, true)) {
                $cat = $name;
            }
        }

        if ($cat !== 'domain') {
            $doc[] = "| `$table` | $cat | $rows | — (skipped) | | | |";
            continue;
        }

        $cols = $pdo->query("select column_name from information_schema.columns where table_schema='$db' and table_name='$table' order by ordinal_position")->fetchAll(PDO::FETCH_COLUMN);
        $keep = array_values(array_filter($cols, fn ($c) => ! preg_match(SENSITIVE_COLS, $c)));
        $dropped = array_values(array_diff($cols, $keep));
        $pk = $pdo->query("select column_name from information_schema.key_column_usage where table_schema='$db' and table_name='$table' and constraint_name='PRIMARY' order by ordinal_position")->fetchAll(PDO::FETCH_COLUMN);

        $raw = "raw.{$src}__{$table}";
        $fdwT = "{$cfg['fdw']}.\"$table\"";
        $q = fn ($c) => '"'.$c.'"';
        $keepQ = implode(', ', array_map($q, $keep));
        $red = $redact["$src.$table"] ?? [];

        $ddl[] = "DROP TABLE IF EXISTS $raw;\nCREATE TABLE $raw AS SELECT $keepQ FROM $fdwT WITH NO DATA;";
        if ($pk) {
            $ddl[] = "ALTER TABLE $raw ADD PRIMARY KEY (".implode(', ', array_map($q, $pk)).');';
        }
        $ddl[] = "ALTER TABLE $raw ADD COLUMN _loaded_at timestamptz NOT NULL DEFAULT now();\n";

        $sel = implode(', ', array_map(
            fn ($c) => in_array($c, $red, true)
                ? 'CASE WHEN '.$q($c)."::text ~* '".REDACT_REGEX."' THEN NULL ELSE ".$q($c).' END'
                : $q($c),
            $keep
        ));
        $load[] = "BEGIN;\nTRUNCATE $raw;\nINSERT INTO $raw ($keepQ)\nSELECT $sel\nFROM $fdwT;\nCOMMIT;\n";

        $verifyRows[] = "SELECT '$raw' AS tbl, (SELECT count(*) FROM $fdwT) AS src, (SELECT count(*) FROM $raw) AS raw_rows";

        $doc[] = "| `$table` | domain | $rows | `{$src}__{$table}` | ".implode(', ', $pk).' | '.implode(', ', $dropped).' | '.implode(', ', $red).' |';
        $included++;
    }
    $summary[$src] = [$included, count($tables)];
}

$ddl[] = "GRANT USAGE ON SCHEMA raw TO cosmax_dwh_etl;\nGRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES IN SCHEMA raw TO cosmax_dwh_etl;\n\nCOMMIT;\n";
$union = implode("\nUNION ALL\n", $verifyRows);
$verify[] = "-- Run each statement separately (Ctrl+Enter on each).\n-- 1) Summary: expect tables_checked = ".count($verifyRows)." and tables_mismatch = 0.\nSELECT count(*) AS tables_checked, count(*) FILTER (WHERE src <> raw_rows) AS tables_mismatch\nFROM (\n$union\n) v;\n";
$verify[] = "-- 2) Only the mismatches (expect zero rows).\nSELECT * FROM (\n$union\n) v\nWHERE src <> raw_rows\nORDER BY tbl;\n";

$doc[] = "\n## Rules applied\n\n- Columns matching `".SENSITIVE_COLS."` are never copied (password hashes, tokens, IP, user agent).\n- `activity_logs` / `audit_logs` `old_data` and `new_data` are set to NULL when they mention password / token / secret (found: 51 `activity_logs` rows, module USER, contain a `password_hash` key).\n- Trial-side links are by **email text** (`created_by`, `approved_by`, `pending_with`, `reviewer_email`, `uploaded_by`, `audit_logs.user_email`) — resolved to `users.id` in `staging`, not here.\n- `raw` keeps MySQL-derived types (e.g. `tinyint` → `smallint`, `json` as exposed by mysql_fdw); casting to boolean/jsonb happens in `staging`.\n";

@mkdir("$root/warehouse/sql", 0777, true);
@mkdir("$root/warehouse/docs", 0777, true);
file_put_contents("$root/warehouse/sql/01_raw_ddl.sql", implode("\n", $ddl));
file_put_contents("$root/warehouse/sql/02_raw_load.sql", implode("\n", $load));
file_put_contents("$root/warehouse/sql/03_verify.sql", implode("\n", $verify));
file_put_contents("$root/warehouse/docs/table_mapping.md", implode("\n", $doc)."\n");

foreach ($summary as $s => [$i, $t]) {
    echo "$s: $i / $t tables loaded\n";
}
